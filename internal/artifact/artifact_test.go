package artifact

import (
	"errors"
	"os"
	"path/filepath"
	"testing"
)

func write(t *testing.T, path, body string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0o700); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(body), 0o600); err != nil {
		t.Fatal(err)
	}
}

func TestInventoryFindsKnownFilesAndSkipsGeneratedOrScratch(t *testing.T) {
	root := t.TempDir()
	claude := filepath.Join(root, "claude")
	codex := filepath.Join(root, "codex")
	hermes := filepath.Join(root, "hermes")
	shared := filepath.Join(root, "agents")
	workspace := filepath.Join(root, "project")
	write(t, filepath.Join(claude, "projects", "project-a", "memory", "MEMORY.md"), "memory")
	write(t, filepath.Join(claude, "projects", "project-a", "memory", "MEMORY.md.lock"), "lock")
	write(t, filepath.Join(codex, "AGENTS.md"), "<!-- Generated by rules-build -->\n")
	write(t, filepath.Join(shared, "RULES.md"), "rules")
	write(t, filepath.Join(shared, "hooks", "guard.sh"), "#!/bin/sh\n")
	write(t, filepath.Join(shared, "hooks", "tests", "guard.bats"), "test")
	write(t, filepath.Join(hermes, "profiles", "work", "SOUL.md"), "soul")
	write(t, filepath.Join(workspace, "AGENTS.md"), "project rules")
	cfg := Config{ClaudeHome: claude, CodexHome: codex, HermesHome: hermes, SharedHome: shared, Workspaces: []string{workspace}}
	items, err := List(cfg)
	if err != nil {
		t.Fatal(err)
	}
	if len(items) != 6 {
		t.Fatalf("items = %+v", items)
	}
	for _, item := range items {
		if item.Name == "AGENTS.md" && item.Provider == "Codex" && (item.Editable || item.Deletable) {
			t.Fatal("generated Codex rules must be read-only")
		}
	}
	filtered, err := Search(cfg, "project rules")
	if err != nil || len(filtered) != 1 || filtered[0].Path != filepath.Join(workspace, "AGENTS.md") {
		t.Fatalf("content search = %+v, %v", filtered, err)
	}
}

func TestSaveChecksRevisionAndDeleteRemovesOnlyListedFile(t *testing.T) {
	root := t.TempDir()
	path := filepath.Join(root, "agents", "RULES.md")
	write(t, path, "before")
	cfg := Config{SharedHome: filepath.Join(root, "agents")}
	items, err := List(cfg)
	if err != nil || len(items) != 1 {
		t.Fatalf("list = %+v, %v", items, err)
	}
	item, body, err := Read(cfg, items[0].ID)
	if err != nil || body != "before" {
		t.Fatalf("read = %+v, %q, %v", item, body, err)
	}
	if err := Save(cfg, item.ID, item.Hash, "after"); err != nil {
		t.Fatal(err)
	}
	if err := Delete(cfg, item.ID, item.Hash); !errors.Is(err, ErrConflict) {
		t.Fatalf("stale delete = %v", err)
	}
	updated, _, err := Read(cfg, item.ID)
	if err != nil {
		t.Fatal(err)
	}
	if err := Delete(cfg, updated.ID, updated.Hash); err != nil {
		t.Fatal(err)
	}
	if _, err := os.Stat(path); !os.IsNotExist(err) {
		t.Fatalf("rule still exists: %v", err)
	}
	if err := Save(cfg, "unknown", updated.Hash, "x"); !errors.Is(err, ErrNotFound) {
		t.Fatalf("arbitrary id = %v", err)
	}
}
