package artifact

import (
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"errors"
	"io"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"time"
)

const (
	maxContent    = 256 << 10
	maxSkillDepth = 2
)

var (
	ErrNotFound       = errors.New("item not found")
	ErrConflict       = errors.New("file changed since it was opened")
	ErrReadOnly       = errors.New("item is read-only")
	ErrTooLarge       = errors.New("file is too large to edit")
	ErrInvalidContent = errors.New("invalid JSON")
)

type Config struct {
	ClaudeHome, CodexHome, HermesHome, SharedHome string
	Workspaces                                    []string
}

type Item struct {
	ID, Kind, Provider, Scope, Name, Path, Hash string
	Size                                        int64
	Modified                                    time.Time
	Editable, Deletable                         bool
	Error                                       string
}

func List(cfg Config) ([]Item, error) {
	items := map[string]Item{}
	add := func(path, kind, provider, scope string, editable, deletable bool) {
		if path == "" {
			return
		}
		info, err := os.Lstat(path)
		if err != nil || !info.Mode().IsRegular() {
			return
		}
		canonical, err := filepath.EvalSymlinks(path)
		if err != nil {
			return
		}
		if _, exists := items[canonical]; exists {
			return
		}
		item := Item{ID: idFor(canonical), Kind: kind, Provider: provider, Scope: scope, Name: filepath.Base(path),
			Path: path, Size: info.Size(), Modified: info.ModTime(), Editable: editable, Deletable: deletable}
		if info.Size() > maxContent {
			item.Error = ErrTooLarge.Error()
			item.Editable, item.Deletable = false, false
			items[canonical] = item
			return
		}
		body, readErr := os.ReadFile(path)
		if readErr != nil {
			item.Error = readErr.Error()
			item.Editable, item.Deletable = false, false
		} else {
			if strings.Contains(string(body[:min(len(body), 512)]), "Generated by rules-build") {
				item.Editable, item.Deletable = false, false
			}
			item.Hash = hash(body)
		}
		items[canonical] = item
	}
	addDir := func(dir, kind, provider, scope string) {
		if dir == "" {
			return
		}
		entries, err := os.ReadDir(dir)
		if err != nil {
			return
		}
		for _, entry := range entries {
			if entry.IsDir() || strings.HasPrefix(entry.Name(), ".") || strings.HasSuffix(entry.Name(), ".lock") {
				continue
			}
			name := entry.Name()
			if kind == "memory" && filepath.Ext(name) != ".md" {
				continue
			}
			if kind == "hook" && !hookFile(name) {
				continue
			}
			if kind == "rule" && filepath.Ext(name) != ".md" && filepath.Ext(name) != ".rules" {
				continue
			}
			add(filepath.Join(dir, name), kind, provider, scope, true, true)
		}
	}
	var addSkills func(dir, provider, scope string, depth int)
	addSkills = func(dir, provider, scope string, depth int) {
		if dir == "" || depth > maxSkillDepth {
			return
		}
		entries, err := os.ReadDir(dir)
		if err != nil {
			return
		}
		for _, entry := range entries {
			sub := filepath.Join(dir, entry.Name())
			if info, err := os.Stat(sub); err != nil || !info.IsDir() || entry.Name() == "node_modules" {
				continue
			}
			skill := filepath.Join(sub, "SKILL.md")
			if _, err := os.Stat(skill); err != nil {
				addSkills(sub, provider, scope, depth+1)
				continue
			}
			add(skill, "skill", provider, scope, true, false)
			if canonical, err := filepath.EvalSymlinks(skill); err == nil {
				if item, ok := items[canonical]; ok && item.Kind == "skill" {
					item.Name = entry.Name()
					items[canonical] = item
				}
			}
		}
	}
	for _, spec := range []struct {
		path, kind, provider, scope string
		editable, deletable         bool
	}{
		{under(cfg.SharedHome, "RULES.md"), "rule", "Shared", "Global", true, true},
		{under(cfg.ClaudeHome, "CLAUDE.md"), "rule", "Claude", "Global", true, true},
		{under(cfg.CodexHome, "AGENTS.md"), "rule", "Codex", "Global", true, true},
		{under(cfg.HermesHome, "SOUL.md"), "rule", "Hermes", "Global", true, true},
		{under(cfg.ClaudeHome, "settings.json"), "hook", "Claude", "Global config", true, false},
		{under(cfg.ClaudeHome, "settings.local.json"), "hook", "Claude", "Global config", true, false},
		{under(cfg.CodexHome, "hooks.json"), "hook", "Codex", "Global config", true, false},
		{under(cfg.HermesHome, "config.yaml"), "hook", "Hermes", "Global config", false, false},
		{under(cfg.HermesHome, "shell-hooks-allowlist.json"), "hook", "Hermes", "Global config", true, false},
	} {
		add(spec.path, spec.kind, spec.provider, spec.scope, spec.editable, spec.deletable)
	}
	addDir(under(cfg.SharedHome, "runtime"), "rule", "Shared", "Global")
	addDir(under(cfg.SharedHome, "hooks"), "hook", "Shared", "Global")
	addDir(under(cfg.ClaudeHome, "hooks"), "hook", "Claude", "Global")
	addDir(under(cfg.CodexHome, "rules"), "rule", "Codex", "Global")
	addDir(under(cfg.CodexHome, "hooks"), "hook", "Codex", "Global")
	addDir(under(cfg.HermesHome, "memories"), "memory", "Hermes", "Global")
	addDir(under(cfg.HermesHome, "hooks"), "hook", "Hermes", "Global")
	addSkills(under(cfg.SharedHome, "skills"), "Shared", "Global", 0)
	addSkills(under(cfg.ClaudeHome, "skills"), "Claude", "Global", 0)
	addSkills(under(cfg.CodexHome, "skills"), "Codex", "Global", 0)
	addSkills(under(cfg.HermesHome, "skills"), "Hermes", "Global", 0)
	for _, project := range glob(under(cfg.ClaudeHome, "projects", "*")) {
		addDir(filepath.Join(project, "memory"), "memory", "Claude", filepath.Base(project))
	}
	for _, profile := range glob(under(cfg.HermesHome, "profiles", "*")) {
		name := filepath.Base(profile)
		add(filepath.Join(profile, "SOUL.md"), "rule", "Hermes", name, true, true)
		addDir(filepath.Join(profile, "memories"), "memory", "Hermes", name)
		addDir(filepath.Join(profile, "hooks"), "hook", "Hermes", name)
		add(filepath.Join(profile, "config.yaml"), "hook", "Hermes", name+" config", false, false)
	}
	seenDirs := map[string]bool{}
	for _, cwd := range cfg.Workspaces {
		if !filepath.IsAbs(cwd) {
			continue
		}
		for dir, depth := filepath.Clean(cwd), 0; depth < 12 && dir != filepath.Dir(dir); dir, depth = filepath.Dir(dir), depth+1 {
			if seenDirs[dir] {
				continue
			}
			seenDirs[dir] = true
			for _, name := range []string{"AGENTS.md", "CLAUDE.md", "MEMORY.md", filepath.Join(".claude", "CLAUDE.md"), filepath.Join(".codex", "AGENTS.md"), filepath.Join(".hermes", "SOUL.md")} {
				kind := "rule"
				if filepath.Base(name) == "MEMORY.md" {
					kind = "memory"
				}
				add(filepath.Join(dir, name), kind, "Project", dir, true, true)
			}
			for _, spec := range []struct{ path, provider string }{{filepath.Join(".claude", "settings.json"), "Claude"}, {filepath.Join(".claude", "settings.local.json"), "Claude"}, {filepath.Join(".codex", "hooks.json"), "Codex"}} {
				add(filepath.Join(dir, spec.path), "hook", spec.provider, dir+" config", true, false)
			}
			addDir(filepath.Join(dir, ".claude", "memory"), "memory", "Claude", dir)
			addDir(filepath.Join(dir, ".claude", "hooks"), "hook", "Claude", dir)
			addDir(filepath.Join(dir, ".codex", "hooks"), "hook", "Codex", dir)
			addDir(filepath.Join(dir, ".hermes", "hooks"), "hook", "Hermes", dir)
			addSkills(filepath.Join(dir, ".claude", "skills"), "Claude", dir, 0)
			addSkills(filepath.Join(dir, ".agents", "skills"), "Shared", dir, 0)
			addSkills(filepath.Join(dir, ".codex", "skills"), "Codex", dir, 0)
			addSkills(filepath.Join(dir, "skills"), "Project", dir, 0)
		}
	}
	out := make([]Item, 0, len(items))
	for _, item := range items {
		out = append(out, item)
	}
	sort.Slice(out, func(i, j int) bool {
		if out[i].Kind != out[j].Kind {
			return out[i].Kind < out[j].Kind
		}
		if out[i].Provider != out[j].Provider {
			return out[i].Provider < out[j].Provider
		}
		return out[i].Path < out[j].Path
	})
	return out, nil
}

func Search(cfg Config, query string) ([]Item, error) {
	items, err := List(cfg)
	if err != nil || strings.TrimSpace(query) == "" {
		return items, err
	}
	query = strings.ToLower(strings.TrimSpace(query))
	filtered := items[:0]
	for _, item := range items {
		metadata := item.Name + " " + item.Path + " " + item.Scope + " " + item.Provider + " " + item.Kind
		if strings.Contains(strings.ToLower(metadata), query) {
			filtered = append(filtered, item)
			continue
		}
		body, err := os.ReadFile(item.Path)
		if err == nil && len(body) <= maxContent && strings.Contains(strings.ToLower(string(body)), query) {
			filtered = append(filtered, item)
		}
	}
	return filtered, nil
}

func Read(cfg Config, id string) (Item, string, error) {
	item, err := find(cfg, id)
	if err != nil {
		return Item{}, "", err
	}
	if item.Error != "" {
		if item.Error == ErrTooLarge.Error() {
			return item, "", ErrTooLarge
		}
		return item, "", errors.New(item.Error)
	}
	body, err := os.ReadFile(item.Path)
	if err != nil {
		return item, "", err
	}
	if len(body) > maxContent {
		return item, "", ErrTooLarge
	}
	item.Hash = hash(body)
	return item, string(body), nil
}

func Save(cfg Config, id, expectedHash, content string) error {
	item, _, err := Read(cfg, id)
	if err != nil {
		return err
	}
	if !item.Editable {
		return ErrReadOnly
	}
	if item.Hash != expectedHash {
		return ErrConflict
	}
	if len(content) > maxContent {
		return ErrTooLarge
	}
	if filepath.Ext(item.Path) == ".json" && !json.Valid([]byte(content)) {
		return ErrInvalidContent
	}
	info, err := os.Lstat(item.Path)
	if err != nil {
		return err
	}
	if !info.Mode().IsRegular() {
		return ErrReadOnly
	}
	tmp, err := os.CreateTemp(filepath.Dir(item.Path), ".appraisal-*")
	if err != nil {
		return err
	}
	defer os.Remove(tmp.Name())
	if err := tmp.Chmod(info.Mode().Perm()); err != nil {
		tmp.Close()
		return err
	}
	if _, err := io.WriteString(tmp, content); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Sync(); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	return os.Rename(tmp.Name(), item.Path)
}

func Delete(cfg Config, id, expectedHash string) error {
	item, _, err := Read(cfg, id)
	if err != nil {
		return err
	}
	if !item.Deletable {
		return ErrReadOnly
	}
	if item.Hash != expectedHash {
		return ErrConflict
	}
	return os.Remove(item.Path)
}

func find(cfg Config, id string) (Item, error) {
	items, err := List(cfg)
	if err != nil {
		return Item{}, err
	}
	for _, item := range items {
		if item.ID == id {
			return item, nil
		}
	}
	return Item{}, ErrNotFound
}

func glob(pattern string) []string { paths, _ := filepath.Glob(pattern); return paths }

func under(root string, parts ...string) string {
	if root == "" {
		return ""
	}
	return filepath.Join(append([]string{root}, parts...)...)
}

func hookFile(name string) bool {
	switch filepath.Ext(name) {
	case ".sh", ".py", ".js", ".ts", ".bash":
		return true
	}
	return false
}

func idFor(path string) string {
	sum := sha256.Sum256([]byte(path))
	return hex.EncodeToString(sum[:12])
}
func hash(content []byte) string { sum := sha256.Sum256(content); return hex.EncodeToString(sum[:]) }
